"""Per-project system prompts: the registry, prompt files, and wrappers.

State is always derived by inspection — which files exist, what they contain —
never recorded. Enable/disable is a rename to <name>.md.off and back, so the
whole feature stays legible in a plain `ls` and survives claude-ui not
existing.

Two properties are load-bearing everywhere below: prompt files are data handed
to claude as flag arguments, never executed or sourced; and the generated zsh
function only honors projects listed in the registry, so a cloned repo cannot
change a claude invocation just by containing files.
"""

from pathlib import Path
import os
import re
import shutil
import subprocess

from .assist import _cli_flags
from .core import (PROJECTS_REGISTRY, _read_json_object, atomic_write,
                   config_dir, project_roots, tilde)


# ---- registry (the read half, project_roots, lives in core.py) ----

_REGISTRY_HEADER = (
    "# Projects registered with claude-ui (Projects tab). One absolute path\n"
    "# per line. Read by claude-ui and by the generated zsh claude function\n"
    "# as an allowlist: prompt files in a repo are ignored unless its root\n"
    "# is listed here.\n")

def registry_path():
    return config_dir() / PROJECTS_REGISTRY

def registry_add(raw):
    p = Path(str(raw or "").strip()).expanduser()
    if not p.is_absolute():
        raise ValueError("project path must be absolute (or start with ~)")
    p = p.resolve()
    if str(p) == "/":
        raise ValueError("refusing to register the filesystem root")
    if not p.is_dir():
        raise ValueError(f"{tilde(p)}: not an existing directory")
    roots = project_roots()
    if p not in roots:
        _write_registry(roots + [p])
    return p

def registry_remove(raw):
    want = Path(str(raw or "").strip()).expanduser()
    # match the exact recorded path or its resolved form — the registry stores
    # resolved paths, but macOS hands /var/... and /private/var/... around
    # interchangeably
    hits = (want, want.resolve())
    roots = project_roots()
    kept = [r for r in roots if r not in hits]
    if len(kept) == len(roots):
        raise ValueError("not a registered project")
    _write_registry(kept)

def _write_registry(roots):
    # whole-file atomic rewrite: the zsh function's grep never sees a torn file
    atomic_write(registry_path(),
                 _REGISTRY_HEADER + "".join(f"{r}\n" for r in roots))


# ---- prompt files ----

REPLACE_MD = "system-prompt.md"
APPEND_MD = "append-system-prompt.md"
OFF_SUFFIX = ".off"
MODES = {"replace": REPLACE_MD, "append": APPEND_MD}

STARTERS = {
    "replace": """\
This file REPLACES Claude Code's entire default system prompt in sessions
launched through the project wrapper. Everything the default prompt provides
— response style, workflow guidance, safety instructions — is gone; only the
built-in tool schemas remain. Spell out whatever you still need:

## Role

You are a coding agent working in this repository.

## Project context

(What this project is, the stack, where things live.)

## Conventions

(Code style, testing expectations, what never to touch.)
""",
    "append": """\
# Project instructions

These lines are APPENDED to Claude Code's default system prompt in sessions
launched through the project wrapper. The default prompt stays intact. Keep
this brief — every session pays for it.
""",
}


# ---- the per-project wrapper script ----

WRAPPER_NAME = "claude.sh"
WRAPPER_MARKER = "generated by claude-ui (projects tab)"
# CDPATH= so an exported CDPATH can neither reroute the cd nor pollute stdout;
# -- guards a dirname starting with -; pwd -P so the flag argument is the
# physical path; exec so the wrapper leaves no extra process behind. `claude`
# resolves via PATH — sh never sees shell aliases, which is what we want.
WRAPPER_SCRIPT = """\
#!/bin/sh
# generated by claude-ui (projects tab) v1 — regenerate there, or edit freely
# (claude-ui only overwrites this file when you click Regenerate).
#
# Runs claude with this project's system-prompt override, if one is enabled:
#   system-prompt.md         replaces the default prompt (--system-prompt-file)
#   append-system-prompt.md  appends to it       (--append-system-prompt-file)
# Rename a file to <name>.md.off to turn it off (or use claude-ui). Prompt
# files are passed to claude as data and never executed.
dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P) || exit 1
if [ -f "$dir/system-prompt.md" ]; then
    exec claude --system-prompt-file "$dir/system-prompt.md" "$@"
elif [ -f "$dir/append-system-prompt.md" ]; then
    exec claude --append-system-prompt-file "$dir/append-system-prompt.md" "$@"
fi
exec claude "$@"
"""


# ---- the global zsh function (installed as a setup piece) ----

ZSH_WRAPPER_NAME = "claude-wrapper.zsh"
ZSH_MARKER = "generated by claude-ui (projects tab)"
ZSHRC_BEGIN = "# >>> claude-ui projects wrapper >>>"
ZSHRC_END = "# <<< claude-ui projects wrapper <<<"

def zsh_function_text():
    """The sourceable function file, with this machine's registry path baked
    in — the file claude-ui actually writes, wherever the config dir is. The
    body is plain POSIX inside the function, so sourcing it from bash works
    too (the mechanism card offers that as a copy-paste line)."""
    return f"""\
# {ZSH_MARKER} v1 — remove from the Setup tab.
# Defines a claude() function that walks up from $PWD looking for
# .claude/system-prompt.md or .claude/append-system-prompt.md, and only
# honors them when the project root is listed in the claude-ui registry —
# so a cloned repo cannot change your claude invocation just by containing
# files. Prompt files are passed to claude as data, never executed or
# sourced. `command claude` bypasses this entirely.
claude() {{
    local registry="{registry_path()}"
    if [ -r "$registry" ]; then
        local dir
        dir="$(pwd -P)"
        while [ -n "$dir" ]; do
            if {{ [ -f "$dir/.claude/system-prompt.md" ] || \\
                 [ -f "$dir/.claude/append-system-prompt.md" ]; }} && \\
                    grep -Fxq -- "$dir" "$registry"; then
                if [ -f "$dir/.claude/system-prompt.md" ]; then
                    command claude --system-prompt-file "$dir/.claude/system-prompt.md" "$@"
                else
                    command claude --append-system-prompt-file "$dir/.claude/append-system-prompt.md" "$@"
                fi
                return
            fi
            [ "$dir" = / ] && break
            dir=$(dirname -- "$dir")
        done
    fi
    command claude "$@"
}}
"""

def zshrc_path():
    return Path(os.environ.get("ZDOTDIR") or Path.home()) / ".zshrc"

def zshrc_block():
    f = config_dir() / ZSH_WRAPPER_NAME
    return (f"{ZSHRC_BEGIN}\n"
            f'[ -f "{f}" ] && source "{f}"\n'
            f"{ZSHRC_END}\n")


# ---- per-project state, derived by looking ----

def project_state(root):
    """Everything the card shows. Never raises for a broken project — a root
    that vanished reports missing: True so the user can see it and remove
    it."""
    root = Path(root)
    cdir = root / ".claude"
    files = {}
    for mode, name in MODES.items():
        files[mode] = {"live": (cdir / name).is_file(),
                       "off": (cdir / (name + OFF_SUFFIX)).is_file()}
    live = [m for m in MODES if files[m]["live"]]
    present = [m for m in MODES if files[m]["live"] or files[m]["off"]]
    styles_dir = cdir / "output-styles"
    return {
        "root": str(root), "tilde": tilde(root),
        "missing": not root.is_dir(), "has_claude_dir": cdir.is_dir(),
        "files": files,
        "mode": ("replace" if "replace" in live else live[0] if live
                 else present[0] if present else None),
        "enabled": bool(live),
        "conflict": (len(live) > 1
                     or any(f["live"] and f["off"] for f in files.values())),
        "wrapper": _wrapper_state(cdir),
        "output_styles": (sorted(p.name for p in styles_dir.glob("*.md"))
                          if styles_dir.is_dir() else []),
        "output_style_setting": _output_style_setting(cdir),
    }

def _wrapper_state(cdir):
    p = cdir / WRAPPER_NAME
    if not p.is_file():
        return "none"
    text = p.read_text(errors="replace")
    if text == WRAPPER_SCRIPT:
        return "current" if os.access(p, os.X_OK) else "not-executable"
    return "stale" if WRAPPER_MARKER in text else "foreign"

def _output_style_setting(cdir):
    # read-only display: which style each project settings file names
    out = {}
    for name in ("settings.json", "settings.local.json"):
        data, _ = _read_json_object(cdir / name)
        if isinstance(data.get("outputStyle"), str):
            out[name] = data["outputStyle"]
    return out


# ---- operations (all re-check registration: these must never become a way
# ---- to write into a directory the user did not register) ----

def _checked_root(raw):
    p = Path(str(raw or "").strip()).expanduser()
    hits = (p, p.resolve())
    for r in project_roots():
        if r in hits:
            return r
    raise ValueError("not a registered project")

def _need_mode(mode):
    if mode not in MODES:
        raise ValueError("mode must be replace or append")

def _pair(cdir, mode):
    live = cdir / MODES[mode]
    return live, cdir / (MODES[mode] + OFF_SUFFIX)

def project_init(root, mode):
    """Starter prompt file (unless either form already exists) + wrapper."""
    root = _checked_root(root)
    _need_mode(mode)
    live, off = _pair(root / ".claude", mode)
    if not live.exists() and not off.exists():
        atomic_write(live, STARTERS[mode])
    wrapper_write(root)

def project_toggle(root, enabled):
    """Rename the current mode's file between <name>.md and <name>.md.off.

    Refuses conflicted layouts rather than guessing: a rename would clobber
    one of two files that both hold user-written prompt text."""
    root = _checked_root(root)
    st = project_state(root)
    if st["mode"] is None:
        raise ValueError("no prompt file to toggle — initialise first")
    if st["conflict"]:
        raise ValueError("conflicting prompt files — resolve in the editor first")
    live, off = _pair(root / ".claude", st["mode"])
    if enabled and off.is_file():
        off.rename(live)
    elif not enabled and live.is_file():
        live.rename(off)

def project_set_mode(root, mode):
    """Make `mode` the live file; the other mode's live file goes to .off.
    A missing target is revived from its .off form, else from the starter."""
    root = _checked_root(root)
    _need_mode(mode)
    cdir = root / ".claude"
    live, off = _pair(cdir, mode)
    other = next(m for m in MODES if m != mode)
    olive, ooff = _pair(cdir, other)
    if live.is_file() and off.is_file():
        raise ValueError(f"both {live.name} and {off.name} exist — "
                         "resolve in the editor first")
    if olive.is_file():
        if ooff.exists():
            raise ValueError(f"both {olive.name} and {ooff.name} exist — "
                             "resolve in the editor first")
        olive.rename(ooff)
    if not live.is_file():
        if off.is_file():
            off.rename(live)
        else:
            atomic_write(live, STARTERS[mode])

def wrapper_write(root, force=False):
    """Write (or refresh) <root>/.claude/claude.sh. A claude.sh we did not
    write (no marker) is refused without force — it is the user's file."""
    root = _checked_root(root)
    p = root / ".claude" / WRAPPER_NAME
    if p.is_file() and not force:
        if WRAPPER_MARKER not in p.read_text(errors="replace"):
            raise ValueError(f"{tilde(p)} exists and wasn't written by "
                             "claude-ui — regenerate with force to replace it")
    atomic_write(p, WRAPPER_SCRIPT, mode=0o755)


# ---- in-UI verification: a free plumbing check and a paid live test ----

TEST_QUESTION = (
    "Quote, verbatim and with nothing else, one full line of the "
    "project-specific instructions that were appended to or replaced your "
    "system prompt.")

def _wrapper_runnable(root):
    """The wrapper we're willing to execute: ours (marker present), for a
    registered root. A foreign claude.sh is the user's own script — we never
    run someone's code for them from a button."""
    root = _checked_root(root)
    p = root / ".claude" / WRAPPER_NAME
    if not p.is_file():
        raise ValueError("no claude.sh here — initialise or create the wrapper first")
    if _wrapper_state(p.parent) == "foreign":
        raise ValueError("claude.sh wasn't written by claude-ui — "
                         "run it yourself in a terminal instead")
    return root, p

def wrapper_check(root):
    """Free: run the wrapper with --version under `sh -x` and report which
    exec branch actually fired. Proves the plumbing without an API call."""
    root, p = _wrapper_runnable(root)
    try:
        r = subprocess.run(["sh", "-x", str(p), "--version"],
                           capture_output=True, text=True, timeout=60,
                           cwd=str(root))
    except (OSError, subprocess.SubprocessError) as e:
        raise ValueError(f"could not run the wrapper: {e}") from None
    traced = [l for l in r.stderr.splitlines() if "exec claude" in l]
    cmd = traced[-1].lstrip("+ ") if traced else ""
    mode = ("replace" if "--system-prompt-file" in cmd
            else "append" if "--append-system-prompt-file" in cmd else "none")
    return {"ok": r.returncode == 0, "mode": mode, "command": cmd,
            "version": r.stdout.strip()[:200],
            "stderr": "" if r.returncode == 0 else r.stderr.strip()[-500:]}

def wrapper_test(root):
    """Paid: one real claude call through the wrapper, asking the model to
    quote the prompt file's first line. Proves the prompt reaches the model,
    not just the command line."""
    root, p = _wrapper_runnable(root)
    st = project_state(root)
    if not st["enabled"]:
        raise ValueError("prompt is disabled — the wrapper would just run "
                         "plain claude; enable it first")
    text = (root / ".claude" / MODES[st["mode"]]).read_text(errors="replace")
    try:
        r = subprocess.run(["sh", str(p), "-p", TEST_QUESTION],
                           capture_output=True, text=True, timeout=240,
                           cwd=str(root))
    except subprocess.TimeoutExpired:
        raise ValueError("claude timed out after 240s") from None
    except (OSError, subprocess.SubprocessError) as e:
        raise ValueError(f"could not run the wrapper: {e}") from None
    if r.returncode != 0:
        raise ValueError("claude failed: "
                         + (r.stderr.strip() or f"exit {r.returncode}")[:500])
    answer = r.stdout.strip()
    # a match against ANY line proves receipt — the model may reasonably pick
    # a body line over a heading. Length guard so "the" can't match anything.
    norm = lambda s: re.sub(r"[^a-z0-9]+", " ", s.lower()).strip()
    na = norm(answer)
    matched_line = ""
    if len(na) >= 8:
        for line in (l.strip() for l in text.splitlines() if l.strip()):
            nl = norm(line)
            if nl and (nl in na or na in nl):
                matched_line = line
                break
    return {"ok": bool(matched_line), "mode": st["mode"],
            "matched_line": matched_line, "answer": answer[:500]}


# ---- assembled payload for GET /api/projects ----

def flag_support():
    exe = shutil.which("claude")
    flags = _cli_flags(exe) if exe else frozenset()
    return {"cli": bool(exe),
            "system_prompt_file": "--system-prompt-file" in flags,
            "append_system_prompt_file": "--append-system-prompt-file" in flags}

def project_suggestions():
    """Transcript-derived cwds not yet registered, filtered to plausible
    project roots: must exist, not be $HOME, not sit inside a .claude dir
    (worktrees), and contain .git or .claude."""
    from .insight import transcript_stats  # local import: heavy module
    have = {str(r) for r in project_roots()}
    out = []
    for cwd in transcript_stats().get("projects", {}):
        p = Path(cwd)
        if (str(p) not in have and str(p) != str(Path.home())
                and "/.claude/" not in str(p) and p.is_dir()
                and ((p / ".git").exists() or (p / ".claude").is_dir())):
            out.append(tilde(p))  # registry_add expanduser()s, so ~ round-trips
    return sorted(out)[:20]

def projects_state():
    return {"registry": tilde(registry_path()),
            "projects": [project_state(r) for r in project_roots()],
            "flags": flag_support(),
            "suggestions": project_suggestions(),
            "zsh": zsh_state(),
            "zsh_file": tilde(config_dir() / ZSH_WRAPPER_NAME)}


# ---- the zsh setup piece (state / apply / remove; registered in setup.py) ----

def zsh_state():
    func = config_dir() / ZSH_WRAPPER_NAME
    rc = zshrc_path()
    try:
        rc_text = rc.read_text()
    except OSError:
        rc_text = ""
    sourced = ZSHRC_BEGIN in rc_text
    current = func.is_file() and func.read_text(errors="replace") == zsh_function_text()
    installed = sourced and current
    if installed:
        detail = f"claude() sourced from {tilde(rc)} — takes effect in new zsh shells"
    elif sourced and func.is_file():
        detail = "installed but outdated — re-apply to refresh"
    elif sourced:
        detail = f"{tilde(rc)} sources it but {tilde(func)} is missing — re-apply"
    elif func.is_file():
        detail = f"{tilde(func)} exists but {tilde(rc)} doesn't source it — apply adds the block"
    else:
        detail = "not installed"
    return {"id": "zsh-claude", "label": "zsh: per-project claude function",
            "desc": "Make plain `claude` pick up a registered project's system "
                    "prompt automatically: a claude() function sourced from "
                    "~/.zshrc. Only projects on the Projects tab are honored; "
                    "`command claude` always bypasses it.",
            "installed": installed, "detail": detail,
            "target": tilde(rc), "removable": sourced or func.is_file()}

def zsh_apply():
    func = config_dir() / ZSH_WRAPPER_NAME
    if func.is_file() and ZSH_MARKER not in func.read_text(errors="replace"):
        raise ValueError(f"{tilde(func)} exists and wasn't written by "
                         "claude-ui — move it aside first")
    atomic_write(func, zsh_function_text())
    rc = zshrc_path()
    text = rc.read_text() if rc.is_file() else ""
    new = _zshrc_without_block(text)
    if new and not new.endswith("\n"):
        new += "\n"
    new += ("\n" if new else "") + zshrc_block()
    if new != text:
        _write_rc(rc, new)

def zsh_remove():
    rc = zshrc_path()
    if rc.is_file():
        text = rc.read_text()
        new = _zshrc_without_block(text)
        if new != text:
            _write_rc(rc, new)
    func = config_dir() / ZSH_WRAPPER_NAME
    if func.is_file() and ZSH_MARKER in func.read_text(errors="replace"):
        func.unlink()

def _zshrc_without_block(text):
    """`text` with our marker block removed. Everything outside the markers
    is the user's — an unterminated block is refused, never guessed at."""
    if ZSHRC_BEGIN not in text:
        return text
    lines = text.splitlines(keepends=True)
    starts = [i for i, l in enumerate(lines) if l.rstrip("\n") == ZSHRC_BEGIN]
    ends = [i for i, l in enumerate(lines) if l.rstrip("\n") == ZSHRC_END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError(f"{tilde(zshrc_path())}: claude-ui marker block is "
                         "damaged — fix it by hand first")
    out = lines[:starts[0]] + lines[ends[0] + 1:]
    # drop the single blank line apply inserted above the block, if it's there
    if starts[0] > 0 and out and starts[0] - 1 < len(out) and out[starts[0] - 1].strip() == "":
        out.pop(starts[0] - 1)
    return "".join(out)

def _write_rc(rc, text):
    # preserve the rc file's own permissions across the tmp+rename
    mode = rc.stat().st_mode & 0o777 if rc.is_file() else None
    atomic_write(rc, text, mode=mode)
