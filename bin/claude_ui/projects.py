def zsh_state():
    func = config_dir() / ZSH_WRAPPER_NAME
    rc = zshrc_path()
    try:
        rc_text = rc.read_text()
    except OSError:
        rc_text = ""
    sourced = ZSHRC_BEGIN in rc_text
    current = func.is_file() and func.read_text(errors="replace") == zsh_function_text()
    installed = sourced and current
    if installed:
        detail = f"claude() sourced from {tilde(rc)} — takes effect in new zsh shells"
    elif sourced and func.is_file():
        detail = "installed but outdated — re-apply to refresh"
    elif sourced:
        detail = f"{tilde(rc)} sources it but {tilde(func)} is missing — re-apply"
    elif func.is_file():
        detail = f"{tilde(func)} exists but {tilde(rc)} doesn't source it — apply adds the block"
    else:
        detail = "not installed"
    return {"id": "zsh-claude", "label": "zsh: per-project claude function",
            "desc": "Make plain `claude` pick up a registered project's system "
                    "prompt automatically: a claude() function sourced from "
                    "~/.zshrc. Only projects on the Projects tab are honored; "
                    "`command claude` always bypasses it.",
            "installed": installed, "detail": detail,
            "target": tilde(rc), "removable": sourced or func.is_file()}

def zsh_apply():
    func = config_dir() / ZSH_WRAPPER_NAME
    if func.is_file() and ZSH_MARKER not in func.read_text(errors="replace"):
        raise ValueError(f"{tilde(func)} exists and wasn't written by "
                         "claude-ui — move it aside first")
    atomic_write(func, zsh_function_text())
    rc = zshrc_path()
    text = rc.read_text() if rc.is_file() else ""
    new = _zshrc_without_block(text)
    if new and not new.endswith("\n"):
        new += "\n"
    new += ("\n" if new else "") + zshrc_block()
    if new != text:
        _write_rc(rc, new)

def zsh_remove():
    rc = zshrc_path()
    if rc.is_file():
        text = rc.read_text()
        new = _zshrc_without_block(text)
        if new != text:
            _write_rc(rc, new)
    func = config_dir() / ZSH_WRAPPER_NAME
    if func.is_file() and ZSH_MARKER in func.read_text(errors="replace"):
        func.unlink()

def _zshrc_without_block(text):
    """`text` with our marker block removed. Everything outside the markers
    is the user's — an unterminated block is refused, never guessed at."""
    if ZSHRC_BEGIN not in text:
        return text
    lines = text.splitlines(keepends=True)
    starts = [i for i, l in enumerate(lines) if l.rstrip("\n") == ZSHRC_BEGIN]
    ends = [i for i, l in enumerate(lines) if l.rstrip("\n") == ZSHRC_END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError(f"{tilde(zshrc_path())}: claude-ui marker block is "
                         "damaged — fix it by hand first")
    out = lines[:starts[0]] + lines[ends[0] + 1:]
    # drop the single blank line apply inserted above the block, if it's there
    if starts[0] > 0 and out and starts[0] - 1 < len(out) and out[starts[0] - 1].strip() == "":
        out.pop(starts[0] - 1)
    return "".join(out)

def _write_rc(rc, text):
    # preserve the rc file's own permissions across the tmp+rename
    mode = rc.stat().st_mode & 0o777 if rc.is_file() else None
    atomic_write(rc, text, mode=mode)
