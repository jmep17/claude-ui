"""Opt-in local-model wrapper: run Claude Code against a local oMLX server.

oMLX (github.com/jundot/omlx) speaks the Anthropic Messages API natively, so
pointing claude at it is pure environment: ANTHROPIC_BASE_URL plus model
names. The whole feature is a generated `claude-local.sh` that exports those
vars and execs claude, plus a `claude-local` zsh function that calls it.
Exported env wins over any settings-file `env` block and dies with the
process, so plain `claude` is never touched — nothing here writes to
settings.json.

Config (base URL, model, API key) lives in machine-local `.claude-ui.json`,
like the config-dir and pricing overrides: a local inference server is a
property of this machine, not of the Claude config dir. State is derived by
inspection, per the setup-piece contract.

Applying also adds a `pricing` override of [0, 0] for the chosen model id, the
documented opt-in that keeps local sessions visible on the Costs tab instead
of being dropped as unpriceable (insight._excluded). The statusline's cost
figure still filters to Claude ids and will ignore local tokens — correct,
since they cost nothing.
"""

import os
import json
import re
import shutil
import subprocess
import urllib.error
import urllib.request

from .core import atomic_write, config_dir, read_cfg, tilde, write_cfg
from .projects import _write_rc, _zshrc_without_block, zshrc_path


DEFAULT_BASE_URL = "http://localhost:8000"

LOCAL_WRAPPER_NAME = "claude-local.sh"
LOCAL_ZSH_NAME = "claude-local.zsh"
LOCAL_MARKER = "generated by claude-ui (local model)"
LOCAL_BEGIN = "# >>> claude-ui local model >>>"
LOCAL_END = "# <<< claude-ui local model <<<"

# Values are spliced into a shell script inside single quotes; these charsets
# are the injection guard. URLs and model ids are conservative — `'`,
# whitespace, `$`, backticks are all refused, so quoting can never be escaped;
# HF-style ids (unsloth/Qwen3-14B-MLX-4bit) fit comfortably. An API key is
# whatever the server generated, so it allows any printable ASCII except `'`
# (the one character that escapes single quotes) — control characters are also
# out, which keeps it header-safe for the probe's Authorization line.
_URL_RE = re.compile(r"^https?://[A-Za-z0-9._:/@%+-]+$")
_VAL_RE = re.compile(r"^[A-Za-z0-9._/:@=+-]*$")
_KEY_RE = re.compile(r"^[ -&(-~]*$")  # printable ASCII minus the single quote


# ---- config, in machine-local .claude-ui.json ----

def local_cfg():
    cfg = read_cfg().get("local_model")
    return cfg if isinstance(cfg, dict) else {}

def local_config_set(base_url, model, api_key):
    base_url = (base_url or "").strip().rstrip("/") or DEFAULT_BASE_URL
    model = (model or "").strip()
    api_key = (api_key or "").strip()
    if not _URL_RE.match(base_url):
        raise ValueError("base URL must be http(s)://… with no spaces or quotes")
    if not _VAL_RE.match(model):
        raise ValueError("model id contains characters we won't put in a shell script")
    if not _KEY_RE.match(api_key):
        raise ValueError("API key contains a quote or control character "
                         "we won't put in a shell script")
    cfg = read_cfg()
    old_model = (cfg.get("local_model") or {}).get("model", "")
    cfg["local_model"] = {"base_url": base_url, "model": model, "api_key": api_key}
    if old_model and old_model != model:
        _pricing_migrate(cfg, old_model, model)
    write_cfg(cfg)
    # keep an installed wrapper in sync — script and config must never drift
    if model and local_wrapper_state() in ("current", "stale"):
        local_wrapper_write()


# ---- the wrapper script ----

def _wrapper_path():
    return config_dir() / LOCAL_WRAPPER_NAME

def local_wrapper_text():
    """The wrapper with this machine's config baked in. Single-quoted values;
    the config validation refuses every character that could escape them."""
    c = local_cfg()
    base = c.get("base_url") or DEFAULT_BASE_URL
    model = c.get("model", "")
    # claude requires a credential; oMLX skips auth on localhost unless an API
    # key was configured, so a placeholder keeps subscription auth out of play
    token = c.get("api_key") or "local"
    return f"""\
#!/bin/sh
# {LOCAL_MARKER} v1 — configure and regenerate from the Setup tab.
#
# Runs claude against the local oMLX server. Plain `claude` is untouched:
# exported env wins over settings.json and only this process gets it.
export ANTHROPIC_BASE_URL='{base}'
export ANTHROPIC_AUTH_TOKEN='{token}'
# every model alias maps to the local id, so no request ever carries a Claude
# model name the local server doesn't have
export ANTHROPIC_MODEL='{model}'
export ANTHROPIC_DEFAULT_HAIKU_MODEL='{model}'
export ANTHROPIC_SMALL_FAST_MODEL='{model}'
# /model picker lists what the server actually serves (its /v1/models), and
# the chosen model is added as a picker entry outright in case discovery
# comes up empty
export CLAUDE_CODE_ENABLE_GATEWAY_MODEL_DISCOVERY=1
export ANTHROPIC_CUSTOM_MODEL_OPTION='{model}'
export ANTHROPIC_CUSTOM_MODEL_OPTION_NAME='{model}'
export ANTHROPIC_CUSTOM_MODEL_OPTION_DESCRIPTION='local model via oMLX'
# a local-model session should work offline and not phone home
export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1
# if the server rejects thinking / context-management fields (HTTP 400), also:
# export CLAUDE_CODE_DISABLE_ADAPTIVE_THINKING=1
# export CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS=1
exec claude "$@"
"""

def local_wrapper_state():
    p = _wrapper_path()
    if not p.is_file():
        return "none"
    text = p.read_text(errors="replace")
    if text == local_wrapper_text():
        return "current" if os.access(p, os.X_OK) else "not-executable"
    return "stale" if LOCAL_MARKER in text else "foreign"

def local_wrapper_write(force=False):
    """Write (or refresh) the wrapper. A claude-local.sh we did not write (no
    marker) is refused without force — it is the user's file."""
    p = _wrapper_path()
    if p.is_file() and not force:
        if LOCAL_MARKER not in p.read_text(errors="replace"):
            raise ValueError(f"{tilde(p)} exists and wasn't written by "
                             "claude-ui — move it aside first")
    # 0o700, not 0o755: the file may contain an API key
    atomic_write(p, local_wrapper_text(), mode=0o700)


# ---- the claude-local zsh function ----

def _zsh_func_path():
    return config_dir() / LOCAL_ZSH_NAME

def local_zsh_text():
    """The sourceable function file. Delegating to the sh wrapper keeps a
    single source of truth for the env vars, and the .sh alone works from
    fish/bash."""
    return (f"# {LOCAL_MARKER} v1 — remove from the Setup tab.\n"
            f"# Runs claude against the local oMLX server; plain `claude` is untouched.\n"
            f'claude-local() {{ "{_wrapper_path()}" "$@"; }}\n')

def local_zshrc_block():
    return (f"{LOCAL_BEGIN}\n"
            f'[ -f "{_zsh_func_path()}" ] && source "{_zsh_func_path()}"\n'
            f"{LOCAL_END}\n")


# ---- pricing override: local tokens are real, their price is $0 ----

def _pricing_add(cfg, model):
    cfg.setdefault("pricing", {})[model] = [0, 0]

def _pricing_drop(cfg, model):
    """Remove our override, but only while it is still exactly [0, 0] — a
    repriced entry is the user's."""
    pricing = cfg.get("pricing")
    if isinstance(pricing, dict) and pricing.get(model) == [0, 0]:
        del pricing[model]
        if not pricing:
            del cfg["pricing"]

def _pricing_migrate(cfg, old_model, new_model):
    pricing = cfg.get("pricing")
    if isinstance(pricing, dict) and pricing.get(old_model) == [0, 0]:
        _pricing_drop(cfg, old_model)
        _pricing_add(cfg, new_model)


# ---- the setup piece: state / apply / remove ----

def local_state():
    """The piece dict for the Setup tab. No network I/O — this renders on
    every tab load; reachability is the explicit probe button's job."""
    c = local_cfg()
    wrapper = local_wrapper_state()
    func = _zsh_func_path()
    rc = zshrc_path()
    try:
        rc_text = rc.read_text()
    except OSError:
        rc_text = ""
    sourced = LOCAL_BEGIN in rc_text
    func_current = func.is_file() and func.read_text(errors="replace") == local_zsh_text()
    installed = wrapper == "current" and sourced and func_current
    if installed:
        detail = (f"claude-local runs {c.get('model')} at "
                  f"{c.get('base_url') or DEFAULT_BASE_URL} — new zsh shells only")
    elif wrapper == "foreign":
        detail = f"{tilde(_wrapper_path())} exists but isn't ours — move it aside first"
    elif wrapper in ("stale", "not-executable"):
        detail = "installed but outdated — re-apply to refresh"
    elif wrapper == "current" or sourced or func.is_file():
        detail = "partly installed — re-apply to finish"
    elif not c.get("model"):
        detail = "not installed — save a base URL and model below first"
    else:
        detail = "not installed"
    return {"id": "local-model", "label": "Local model: claude-local (oMLX)",
            "desc": "An opt-in `claude-local` command that runs Claude Code "
                    "against a local oMLX server (Anthropic-compatible, no "
                    "proxy). Plain `claude` keeps using the Anthropic API; "
                    "settings.json is never touched.",
            "installed": installed, "detail": detail,
            "target": tilde(_wrapper_path()),
            "removable": wrapper in ("current", "stale", "not-executable")
                         or sourced or func.is_file(),
            "notes": [f"{tilde(_wrapper_path())} — env exports + exec claude",
                      f"{tilde(func)} — the claude-local() function",
                      f"{tilde(rc)} — one marker block sourcing it",
                      f".claude-ui.json pricing[{c.get('model') or '<model>'}]"
                      " = [0, 0] so local sessions show on the Costs tab"],
            "config": {"base_url": c.get("base_url", ""),
                       "model": c.get("model", ""),
                       "api_key": c.get("api_key", "")},
            "wrapper": wrapper,
            "omlx_cli": bool(shutil.which("omlx"))}

def local_apply():
    cfg = read_cfg()
    model = (cfg.get("local_model") or {}).get("model", "")
    if not model:
        raise ValueError("pick a model first — fetch the list from the "
                         "running oMLX server, then Save")
    local_wrapper_write()
    func = _zsh_func_path()
    if func.is_file() and LOCAL_MARKER not in func.read_text(errors="replace"):
        raise ValueError(f"{tilde(func)} exists and wasn't written by "
                         "claude-ui — move it aside first")
    atomic_write(func, local_zsh_text())
    rc = zshrc_path()
    text = rc.read_text() if rc.is_file() else ""
    new = _zshrc_without_block(text, LOCAL_BEGIN, LOCAL_END)
    if new and not new.endswith("\n"):
        new += "\n"
    new += ("\n" if new else "") + local_zshrc_block()
    if new != text:
        _write_rc(rc, new)
    _pricing_add(cfg, model)
    write_cfg(cfg)

def local_remove():
    rc = zshrc_path()
    if rc.is_file():
        text = rc.read_text()
        new = _zshrc_without_block(text, LOCAL_BEGIN, LOCAL_END)
        if new != text:
            _write_rc(rc, new)
    for p in (_zsh_func_path(), _wrapper_path()):
        if p.is_file() and LOCAL_MARKER in p.read_text(errors="replace"):
            p.unlink()
    cfg = read_cfg()
    model = (cfg.get("local_model") or {}).get("model", "")
    if model:
        _pricing_drop(cfg, model)
    # the local_model config itself stays — it is user input; re-apply restores
    write_cfg(cfg)


# ---- probes: a free reachability check and a live generation ----

def local_probe(base_url=None):
    """Free: GET /v1/models off the server. An unreachable server is the
    expected 'oMLX not running' answer, so this returns ok: False rather than
    raising."""
    base = (base_url or "").strip().rstrip("/") or local_cfg().get("base_url") \
        or DEFAULT_BASE_URL
    if not _URL_RE.match(base):
        return {"ok": False, "models": [],
                "detail": "base URL must be http(s)://… with no spaces or quotes"}
    url = base + "/v1/models"
    req = urllib.request.Request(url)
    key = local_cfg().get("api_key")
    if key:
        req.add_header("Authorization", "Bearer " + key)
    try:
        with urllib.request.urlopen(req, timeout=5) as resp:
            data = json.loads(resp.read().decode("utf-8", "replace"))
    except urllib.error.HTTPError as e:
        hint = " — set the API key" if e.code in (401, 403) else ""
        return {"ok": False, "models": [],
                "detail": f"server reachable but HTTP {e.code}{hint}"}
    except (urllib.error.URLError, OSError) as e:
        return {"ok": False, "models": [],
                "detail": str(getattr(e, "reason", e) or e)}
    except json.JSONDecodeError:
        return {"ok": False, "models": [],
                "detail": f"{url} did not return JSON — is that really oMLX?"}
    rows = data.get("data") if isinstance(data, dict) else None
    models = sorted(r["id"] for r in rows or []
                    if isinstance(r, dict) and isinstance(r.get("id"), str))
    return {"ok": True, "models": models,
            "detail": f"{len(models)} model{'s' if len(models) != 1 else ''} at {base}"}

LOCAL_TEST_PROMPT = "Reply with exactly: LOCAL OK"

def local_test():
    """One real generation through the wrapper. Free in dollars, but it runs
    inference on the local machine — behind an explicit button only."""
    p = _wrapper_path()
    st = local_wrapper_state()
    if st == "none":
        raise ValueError("no wrapper yet — apply the piece first")
    if st == "foreign":
        raise ValueError(f"{tilde(p)} wasn't written by claude-ui — "
                         "run it yourself in a terminal instead")
    try:
        r = subprocess.run(["sh", str(p), "-p", LOCAL_TEST_PROMPT],
                           capture_output=True, text=True, timeout=240,
                           cwd=os.path.expanduser("~"))
    except subprocess.TimeoutExpired:
        raise ValueError("claude timed out after 240s — is the model loaded? "
                         "(first load can be slow)") from None
    except (OSError, subprocess.SubprocessError) as e:
        raise ValueError(f"could not run the wrapper: {e}") from None
    if r.returncode != 0:
        raise ValueError("claude failed: "
                         + (r.stderr.strip() or f"exit {r.returncode}")[:500])
    answer = r.stdout.strip()
    ok = "local ok" in re.sub(r"[^a-z0-9]+", " ", answer.lower())
    return {"ok": ok, "answer": answer[:500]}
