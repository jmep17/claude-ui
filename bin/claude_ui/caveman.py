"""Two caveman skills as a setup piece: installed alone, one on by default.

Upstream ships caveman as a *plugin* — 21 skill directories, 5 commands, 3
cavecrew agents, an MCP delegate and a statusline badge — and Claude Code
enables a plugin whole. The parts worth having are two of those skills,
vendored here under data/presets/skills/ the way data/presets/output-styles/
adhd.md is: `caveman` itself, one self-contained markdown file, and
`caveman-compress`, a small tree whose scripts/ package rewrites a memory file
in place. Installing them needs no marketplace, no `claude plugin install`, and
no network, which is what makes a second machine a checkout plus one Apply.

Only `caveman` is hooked. `caveman-compress` goes in as an ordinary skill you
invoke — it overwrites the file you point it at (keeping a backup outside the
tree) by shelling out to the local `claude` CLI, which is not something to put
on a hook.

A skill on its own is not on by default: Claude Code loads the frontmatter name
and description and pulls the body in only when it decides to, so a bare install
of `caveman` still means typing it. Upstream's always-on behaviour comes from a hook,
not the skill — plugin.json registers SessionStart -> caveman-activate.js, which
prints the ruleset into the session. This piece keeps that mechanism and drops
the rest: a generated script does the printing, and the level file it reads is
the same <config>/.caveman-active path and format upstream uses, so the two
remain compatible if the real plugin is ever installed alongside.

The SessionStart block carries no matcher, exactly as upstream's plugin.json
does, so it fires for every start — including `compact`, which is what stops the
rules being quietly lost to a compaction mid-session.

Unlike every other piece here, this one has to merge into settings.json's
`hooks`, which is a list of blocks the user also owns (four handoff blocks, in
the case this was written for). settings_set_many() merges dotted paths by
walking dicts, so writing hooks.SessionStart would replace that event's whole
array; _strip_ours() below does the read-modify-write instead, keyed on the
command string naming our own script. That is the same ownership test statusline
makes before clearing statusLine, and the same one preset_remove makes before
deleting a key: touch it only while it still says what we wrote.
"""

from pathlib import Path
import json

from .core import (atomic_write, atomic_write_bytes, config_dir,
                   set_frontmatter_key, tilde)
from .items import item_create, resolve_item
from .settings import settings_set, settings_state

UPSTREAM = "https://github.com/JuliusBrussee/caveman"
REF = "v2.0.0"

# Not SOURCE_KEY: that one means "adopted from a plugin", and adopted_items()
# resolves it back to an installed plugin to compute drift. Stamping it here
# would make the skill report as an adoption whose plugin has gone missing,
# because the plugin is precisely what we are not installing.
PRESET_KEY = "x-claude-ui-preset"
PRESET_REF = f"caveman@{REF}"

PRESET_DIR = Path(__file__).resolve().parent / "data" / "presets" / "skills"

# The always-on one: the hook injects this skill's body and no other.
SKILL = "caveman"

# Installed alongside, but ordinary — no hook, invoked as /caveman-compress.
# It is a tree, not a file: SKILL.md drives scripts/ beside it, which rewrite
# the file you point them at (keeping a backup out of tree) by calling the local
# `claude` CLI, or the Anthropic SDK when ANTHROPIC_API_KEY is set.
EXTRA_SKILLS = ("caveman-compress",)
ALL_SKILLS = (SKILL,) + EXTRA_SKILLS

PAYLOAD = PRESET_DIR / SKILL / "SKILL.md"

LEVELS = ("lite", "full", "ultra", "wenyan-lite", "wenyan-full", "wenyan-ultra")
DEFAULT_LEVEL = "full"

ACTIVATE_SCRIPT = '''#!/usr/bin/env python3
# Generated by claude-ui (Setup tab -> caveman) — Apply overwrites this file.
# SessionStart hook: puts the caveman ruleset into the session's context, so the
# skill is on without anyone typing /caveman. SessionStart is one of the three
# events whose stdout Claude Code adds to the context; see
# https://code.claude.com/docs/en/hooks
#
# Off switch — this then prints nothing and exits 0:
#     rm __FLAGTILDE__
import json, sys

FLAG = __FLAG__
SKILL = __SKILL__
LEVELS = __LEVELS__
DEFAULT = __DEFAULT__

def body(text):
    """Everything after the YAML frontmatter block."""
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                return "\\n".join(lines[i + 1:]).strip()
    return text.strip()

try:
    level = open(FLAG).read().strip()
except OSError:
    sys.exit(0)                      # no level file: caveman is off
if level not in LEVELS:
    level = DEFAULT
try:
    rules = body(open(SKILL).read())
except OSError:
    sys.exit(0)                      # skill deleted from under us
if not rules:
    sys.exit(0)
sys.stdout.write(json.dumps({"hookSpecificOutput": {
    "hookEventName": "SessionStart",
    "additionalContext": "CAVEMAN MODE ACTIVE - level: %s\\n\\n%s" % (level, rules),
}}))
'''


def caveman_paths():
    """(skill SKILL.md, generated hook script, level flag)."""
    cfg = config_dir()
    return (cfg / "skills" / "caveman" / "SKILL.md",
            cfg / "hooks" / "caveman-activate.py",
            cfg / ".caveman-active")


def _payload(name=SKILL):
    """The vendored SKILL.md with the upstream ref stamped into it.

    The files on disk are kept byte-identical to upstream so
    tools/sync_caveman_skill.py can diff them without knowing anything about us;
    the stamp is added here, on the way out."""
    try:
        text = (PRESET_DIR / name / "SKILL.md").read_text()
    except OSError as e:
        raise ValueError(f"vendored {name} SKILL.md is unreadable ({e})")
    if not text.strip():
        raise ValueError(f"vendored {name} SKILL.md is empty")
    return set_frontmatter_key(text, PRESET_KEY, PRESET_REF)


def _payload_files(name):
    """(relative path, bytes) for every vendored file of a skill, SKILL.md
    carrying its stamp. caveman is one markdown file; caveman-compress is a
    tree, so this walks rather than assuming."""
    root = PRESET_DIR / name
    if not root.is_dir():
        raise ValueError(f"vendored {name} skill is missing")
    out = [(Path("SKILL.md"), _payload(name).encode())]
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or rel == Path("SKILL.md") or p.name.startswith("."):
            continue
        out.append((rel, p.read_bytes()))
    return out


def _skill_dir(name):
    return config_dir() / "skills" / name


def _script():
    skillp, _, flagp = caveman_paths()
    return (ACTIVATE_SCRIPT
            .replace("__FLAGTILDE__", tilde(flagp))
            .replace("__FLAG__", json.dumps(str(flagp)))
            .replace("__SKILL__", json.dumps(str(skillp)))
            .replace("__LEVELS__", repr(LEVELS))
            .replace("__DEFAULT__", repr(DEFAULT_LEVEL)))


def _commands():
    """Both spellings of our hook command, so ownership survives a hand-edit
    that expanded or collapsed the home directory — statusline's test."""
    scriptp = caveman_paths()[1]
    return (tilde(scriptp), str(scriptp))


def _block():
    return {"hooks": [{"type": "command", "command": tilde(caveman_paths()[1]),
                       "timeout": 5}]}


def _hooks_of(data):
    hooks = data.get("hooks")
    if hooks is None:
        return {}
    if not isinstance(hooks, dict):
        raise ValueError("settings.json: hooks is not a JSON object — "
                         "fix it by hand first")
    return json.loads(json.dumps(hooks))       # deep copy; it is plain JSON


def _strip_ours(hooks):
    """(hooks without our SessionStart entry, whether one was there).

    Surgical rather than wholesale: an entry of ours is dropped from its block,
    and the block goes only when it held nothing else. A user who parked another
    command in the same block keeps it."""
    cmds = _commands()
    out = dict(hooks)
    blocks = out.get("SessionStart")
    if not isinstance(blocks, list):
        return out, False
    found = False
    kept = []
    for b in blocks:
        if not isinstance(b, dict) or not isinstance(b.get("hooks"), list):
            kept.append(b)
            continue
        inner = [h for h in b["hooks"]
                 if not (isinstance(h, dict) and h.get("command") in cmds)]
        if len(inner) != len(b["hooks"]):
            found = True
        if inner:
            kept.append({**b, "hooks": inner})
    if kept:
        out["SessionStart"] = kept
    else:
        out.pop("SessionStart", None)
    return out, found


def caveman_level():
    flagp = caveman_paths()[2]
    try:
        level = flagp.read_text().strip()
    except OSError:
        return None
    return level if level in LEVELS else DEFAULT_LEVEL


def caveman_level_set(level):
    """Set the intensity. Takes effect at the next session start, which is when
    the hook reads the file."""
    if level not in LEVELS:
        raise ValueError(f"unknown caveman level: {level}")
    flagp = caveman_paths()[2]
    if caveman_level() != level:
        atomic_write(flagp, level + "\n")


def _skill_status(name):
    """(installed, note) for one skill."""
    live = _skill_dir(name) / "SKILL.md"
    if live.is_file():
        try:
            same = live.read_text() == _payload(name)
        except (OSError, ValueError):
            same = False
        return True, ("installed" if same else
                      "installed, and edited since — Apply leaves it alone")
    parked = resolve_item("skills", name, False, None)
    if parked.exists() or parked.is_symlink():
        return False, f"disabled, parked at {tilde(parked)}"
    return False, "not installed"


def _install_skill(name, files):
    """Write the vendored tree as an ordinary personal skill. A skill already
    there is left exactly as it is — including a copy the user has edited."""
    root = _skill_dir(name)
    if (root / "SKILL.md").is_file():
        return
    parked = resolve_item("skills", name, False, None)
    if parked.exists() or parked.is_symlink():
        raise ValueError(f"a {name} skill is disabled at {tilde(parked)} — "
                         "enable or delete it on the Skills tab first")
    # SKILL.md through item_create, so the one create path keeps owning the
    # name check and the item shape; the rest of the tree beside it.
    item_create("skills", name, _payload(name))
    for rel, data in files:
        if rel != Path("SKILL.md"):
            atomic_write_bytes(root / rel, data)


def caveman_state():
    skillp, scriptp, flagp = caveman_paths()
    st = settings_state()
    status = {n: _skill_status(n) for n in ALL_SKILLS}
    have_skill = all(ok for ok, _ in status.values())
    hooked = False
    err = st["error"]
    if not err:
        try:
            hooked = _strip_ours(_hooks_of(st["data"]))[1]
        except ValueError as e:
            err = str(e)
    level = caveman_level()
    installed = bool(have_skill and scriptp.is_file() and hooked and level)

    if err:
        detail = f"settings.json is unreadable ({err}) — fix it by hand first"
    elif installed:
        detail = f"on at level {level}, injected by {tilde(scriptp)} every session start"
    elif not (any(ok for ok, _ in status.values()) or scriptp.is_file() or hooked):
        detail = ("installs two skills and one SessionStart hook; "
                  "no plugin, no marketplace")
    elif have_skill and scriptp.is_file() and hooked and not level:
        detail = ("installed but switched off — the level file is gone; "
                  "Apply turns it back on")
    else:
        missing = [w for w, ok in (
            *((f"the {n} skill", ok) for n, (ok, _) in status.items()),
            ("the hook script", scriptp.is_file()),
            ("the settings.json hook", hooked)) if not ok]
        detail = "half installed — Apply adds " + ", ".join(missing)

    return {
        "id": "caveman",
        "label": "Caveman mode",
        "desc": (f"Install two of caveman's skills ({REF}, vendored) into "
                 "skills/ and add a SessionStart hook that turns the first on "
                 "without /caveman. Costs about 1.5k tokens of context per "
                 "session and claims a measured 65% cut in output tokens. "
                 f"Off switch: delete {tilde(flagp)}. No plugin is installed, "
                 "so the other 19 skills, 5 commands and 3 agents stay out"),
        "installed": installed,
        "detail": detail,
        "target": tilde(scriptp),
        "removable": True,
        "config": {"level": level, "levels": list(LEVELS)},
        "notes_label": "What it writes (two skills, two files, one settings.json key)",
        "notes": [
            f"{tilde(_skill_dir(SKILL))}/ — the always-on skill, the one the "
            f"hook injects — {status[SKILL][1]}",
            f"{tilde(_skill_dir('caveman-compress'))}/ — /caveman-compress: "
            "SKILL.md plus a scripts/ package that rewrites a memory file in "
            "place, keeping a backup outside the tree. No hook; you invoke it — "
            f"{status['caveman-compress'][1]}",
            f"{tilde(scriptp)} — generated hook, prints the ruleset at every "
            "session start",
            f"{tilde(flagp)} — the level"
            + (f", currently {level}" if level else ", currently absent (off)"),
            "settings.json hooks.SessionStart — one block appended; any blocks "
            "already there are left byte-identical",
            f"all vendored from {UPSTREAM} at {REF}",
        ],
    }


def caveman_apply():
    """Install the skills, generate the hook, turn it on.

    Every write is guarded on already being right, so a re-apply touches nothing
    — the same contract the token-saver preset holds.
    """
    _, scriptp, flagp = caveman_paths()
    payloads = {n: _payload_files(n) for n in ALL_SKILLS}   # loud before writing

    st = settings_state()
    if st["error"]:
        raise ValueError(f"settings.json has invalid JSON — fix it by hand "
                         f"first ({st['error']})")
    hooks = _hooks_of(st["data"])          # loud if hooks is the wrong shape

    for name, files in payloads.items():
        _install_skill(name, files)

    script = _script()
    try:
        current = scriptp.read_text()
    except OSError:
        current = None
    if current != script:
        atomic_write_bytes(scriptp, script.encode(), mode=0o755)

    if caveman_level() is None:
        atomic_write(flagp, DEFAULT_LEVEL + "\n")

    stripped, _ = _strip_ours(hooks)
    stripped.setdefault("SessionStart", []).append(_block())
    settings_set("hooks", stripped)        # no-op when it already says this


def caveman_remove():
    """Drop the hook and the generated script. The skills stay: once written
    they are ordinary items, and the Skills tab is where items are deleted. The
    level file stays too, so a re-apply comes back at the level you chose —
    statusline keeps its statusline.json for the same reason."""
    scriptp = caveman_paths()[1]
    scriptp.unlink(missing_ok=True)
    st = settings_state()
    if st["error"]:
        return                              # nothing safe to do; state says so
    try:
        hooks = _hooks_of(st["data"])
    except ValueError:
        return
    stripped, found = _strip_ours(hooks)
    if found:
        settings_set("hooks", stripped or None)
